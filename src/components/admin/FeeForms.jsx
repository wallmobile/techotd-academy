"use client";

import { useActionState } from "react";
import { useFormStatus } from "react-dom";
import { Input } from "@/components/ui/Input";
import { Select } from "@/components/ui/Select";
import { Textarea } from "@/components/ui/Textarea";
import { Button } from "@/components/ui/Button";
import { MANUAL_PAYMENT_METHODS, PAYMENT_METHOD_LABELS } from "@/constants/fees";
import {
  assignFeeAction,
  updateFeeAction,
  cancelFeeAction,
  recordPaymentAction,
  voidPaymentAction,
} from "@/lib/fees/actions";

const idle = { status: "idle" };

function Submit({ children, variant = "primary", size = "md" }) {
  const { pending } = useFormStatus();
  return (
    <Button type="submit" variant={variant} size={size} loading={pending} disabled={pending}>
      {children}
    </Button>
  );
}

function Feedback({ state }) {
  if (state.status === "error") {
    return (
      <p role="alert" className="rounded-sm border border-danger/30 bg-danger/5 px-3 py-2 text-sm text-danger">
        {state.formError}
      </p>
    );
  }
  if (state.status === "success") {
    return (
      <p role="status" className="text-sm font-medium text-success">
        {state.message}
      </p>
    );
  }
  return null;
}

/** Assign a fee to one enrollment. Amounts are decimal strings; the server parses them to integer minor units. */
export function AssignFeeForm({ enrollmentId, currencies, defaultCurrency }) {
  const [state, action] = useActionState(assignFeeAction, idle);
  const v = state.values || {};
  return (
    <form action={action} className="flex flex-col gap-4">
      <input type="hidden" name="enrollmentId" value={enrollmentId} />
      <Feedback state={state} />
      <Select label="Currency" id="currency" name="currency" defaultValue={v.currency || defaultCurrency}>
        {currencies.map((c) => (
          <option key={c} value={c}>
            {c}
          </option>
        ))}
      </Select>
      <Input label="Total fee" id="total" name="total" inputMode="decimal" placeholder="e.g. 25000" defaultValue={v.total || ""} required />
      <Input label="Discount (optional)" id="discount" name="discount" inputMode="decimal" placeholder="0" defaultValue={v.discount || ""} />
      <Input label="Due date (optional)" id="dueDate" name="dueDate" type="date" defaultValue={v.dueDate || ""} />
      <Textarea label="Internal note (optional)" id="note" name="note" rows={2} maxLength={500} defaultValue={v.note || ""} />
      <div>
        <Submit>Assign fee</Submit>
      </div>
    </form>
  );
}

