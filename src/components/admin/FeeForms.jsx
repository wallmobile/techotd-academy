/**
 * Manual (offline) payment. `idempotencyKey` is generated by the server for
 * this render, so an accidental double-submit records once.
 */
export function RecordPaymentForm({ feePlanId, idempotencyKey, today }) {
  const [state, action] = useActionState(recordPaymentAction, idle);
  return (
    <form action={action} className="flex flex-col gap-3">
      <input type="hidden" name="feePlanId" value={feePlanId} />
      <input type="hidden" name="idempotencyKey" value={idempotencyKey} />
      <Input label="Amount received" id="amount" name="amount" inputMode="decimal" placeholder="e.g. 5000" required />
      <Select label="Method" id="method" name="method" defaultValue="" required>
        <option value="" disabled>
          Select a method…
        </option>
        {MANUAL_PAYMENT_METHODS.map((m) => (
          <option key={m} value={m}>
            {PAYMENT_METHOD_LABELS[m]}
          </option>
        ))}
      </Select>
      <Input label="Date received" id="paidOn" name="paidOn" type="date" defaultValue={today} max={today} required />
      <Input label="Reference / note (optional)" id="note" name="note" maxLength={500} placeholder="Cheque no., UTR, who paid…" />
      <p className="text-xs text-muted">Recorded as a manual entry in your name. It is not a gateway-verified payment.</p>
      <div>
        <Submit>Record payment</Submit>
      </div>
      <Feedback state={state} />
    </form>
  );
}

export function VoidPaymentForm({ paymentId }) {
  const [state, action] = useActionState(voidPaymentAction, idle);
  return (
    <form action={action} className="flex flex-wrap items-end gap-2">
      <input type="hidden" name="paymentId" value={paymentId} />
      <div className="min-w-[10rem] flex-1">
        <Input label="Void reason" id={`reason-${paymentId}`} name="reason" maxLength={500} required />
      </div>
      <Submit variant="outline" size="sm">
        Void
      </Submit>
      <div className="w-full">
        <Feedback state={state} />
      </div>
    </form>
  );
}
