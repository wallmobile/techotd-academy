"use client";

import Link from "next/link";
import { useActionState } from "react";
import { useFormStatus } from "react-dom";
import { Card } from "@/components/ui/Card";
import { Select } from "@/components/ui/Select";
import { Textarea } from "@/components/ui/Textarea";
import { Input } from "@/components/ui/Input";
import { Button } from "@/components/ui/Button";
import { Badge } from "@/components/ui/Badge";
import { askAssistantAction, recommendCoursesAction } from "@/lib/ai/actions";

const idle = { status: "idle" };

function Submit({ children }) {
  const { pending } = useFormStatus();
  return (
    <Button type="submit" loading={pending} disabled={pending}>
      {children}
    </Button>
  );
}

/**
 * Both panels render AI/catalog output strictly as plain text (React escapes
 * it); nothing is injected as HTML or markdown, and no result changes any
 * record.
 */
export function AskAssistantPanel({ aiConfigured, courses }) {
  const [state, action] = useActionState(askAssistantAction, idle);

  return (
    <Card>
      <h2 className="text-sm font-semibold text-dark">Ask the learning assistant</h2>
      {!aiConfigured && (
        <p role="status" className="mt-3 rounded-sm border border-border bg-surface px-3 py-2 text-sm text-muted">
          The AI assistant isn&apos;t set up on this server yet, so it can&apos;t answer questions. Course recommendations below still work.
        </p>
      )}
      <form action={action} className="mt-4 flex flex-col gap-3">
        <Textarea
          label="Your question"
          id="question"
          name="question"
          rows={4}
          maxLength={1000}
          required
          disabled={!aiConfigured}
          defaultValue={state.question || ""}
          placeholder="e.g. Explain the difference between props and state in React"
        />
        <Select label="Use an outline of one of your courses (optional)" id="courseSlug" name="courseSlug" defaultValue="" disabled={!aiConfigured}>
          <option value="">No course</option>
          {courses.map((c) => (
            <option key={c.slug} value={c.slug}>
              {c.title}
            </option>
          ))}
        </Select>
        <div>{aiConfigured ? <Submit>Ask</Submit> : <Button type="button" disabled>Ask</Button>}</div>
      </form>

      {state.status === "error" && (
        <p role="alert" className="mt-4 rounded-sm border border-danger/30 bg-danger/5 px-3 py-2 text-sm text-danger">
          {state.message}
        </p>
      )}
      {state.status === "success" && (
        <div className="mt-4 flex flex-col gap-2" aria-live="polite">
          <div className="flex items-center gap-2">
            <Badge variant="secondary">AI-generated</Badge>
            {state.groundedInCourse && <span className="text-xs text-muted">Used the outline of your selected course</span>}
          </div>
          <p className="whitespace-pre-wrap break-words text-sm text-text">{state.answer}</p>
          <p className="text-xs text-muted">
            This answer is generated by an AI model and can be wrong. It is not official Academy information — check important details with your
            trainer.
          </p>
        </div>
      )}
    </Card>
  );
}

export function RecommendPanel({ aiConfigured }) {
  const [state, action] = useActionState(recommendCoursesAction, idle);

  return (
    <Card>
      <h2 className="text-sm font-semibold text-dark">Find courses for your interests</h2>
      <form action={action} className="mt-4 flex flex-col gap-3">
        <Input
          label="What would you like to learn?"
          id="interests"
          name="interests"
          maxLength={300}
          required
          defaultValue={state.interests || ""}
          placeholder="e.g. build web apps with React and Node"
        />
        <p className="text-xs text-muted">
          {aiConfigured
            ? "Matches come from the Academy catalog; the AI only helps choose and explain among them."
            : "Matches come from the Academy catalog by keyword (no AI is configured)."}
        </p>
        <div>
          <Submit>Suggest courses</Submit>
        </div>
      </form>

      {state.status === "error" && (
        <p role="alert" className="mt-4 rounded-sm border border-danger/30 bg-danger/5 px-3 py-2 text-sm text-danger">
          {state.message}
        </p>
      )}
      {state.status === "success" && (
        <div className="mt-4 flex flex-col gap-3" aria-live="polite">
          <div className="flex items-center gap-2">
            <Badge variant={state.source === "ai" ? "secondary" : "neutral"}>{state.source === "ai" ? "AI-assisted" : "Catalog match"}</Badge>
          </div>
          {state.note && <p className="text-sm text-muted">{state.note}</p>}
          {state.picks.length > 0 && (
            <ul className="flex flex-col gap-3">
              {state.picks.map((p) => (
                <li key={p.slug} className="rounded-sm border border-border p-3">
                  <Link href={`/courses/${p.slug}`} className="text-sm font-semibold text-dark hover:text-primary">
                    {p.title}
                  </Link>
                  <p className="text-xs text-muted">
                    {p.category} · {p.level}
                  </p>
                  <p className="mt-1 break-words text-sm text-text">{p.reason}</p>
                </li>
              ))}
            </ul>
          )}
          <p className="text-xs text-muted">Suggestions are learning options only — they don&apos;t guarantee a job or outcome.</p>
        </div>
      )}
    </Card>
  );
}
